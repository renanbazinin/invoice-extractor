import type { CanonicalField, DecimalString, DocumentType } from '../model/types'

/** Languages of the lexicon. 'intl' is for tokens shared by every language (IBAN, SWIFT). */
export type Lang = 'he' | 'en' | 'de' | 'fr' | 'es' | 'it' | 'nl' | 'pt' | 'intl'

/**
 * 'strong': the phrase names the concept on its own ("מספר חשבונית", "Invoice No.").
 * 'weak': the phrase often names the concept but needs context to be trusted ("סה"כ", "Date",
 * "Total"), so interpretation must not treat a weak label as an independent confirmation.
 */
export type Strength = 'strong' | 'weak'

/**
 * What a concept is about:
 * - 'field': names a canonical field directly (invoice_number, total, ...).
 * - 'party_attr': a party sub-field (tax id, phone, ...) whose owner (supplier/customer) comes from
 *   a role marker or the position on the page.
 * - 'role': a party marker (לכבוד, Bill to, From, ...).
 * - 'column': a line-item table column header.
 * - 'doctype': a document title (חשבונית מס, Credit note, ...).
 * - 'trap': looks like a target but is not one (page subtotal, customer number, fax, ...).
 * - 'other': known labels outside the schema (reference, notes, period, ...), kept for discovery.
 */
export type ConceptKind = 'field' | 'party_attr' | 'role' | 'column' | 'doctype' | 'trap' | 'other'

/** What kind of value a label or a piece of text holds. */
export type ValueKind =
  | 'amount'
  | 'percent'
  | 'date'
  | 'id'
  | 'tax_id'
  | 'phone'
  | 'email'
  | 'iban'
  | 'bank_account'
  | 'currency'
  | 'quantity'
  | 'text'

/**
 * One concept of the lexicon. Phrases are plain strings per language; a leading '~' marks a weak
 * phrase, a leading '=' (after any '~') forbids Hebrew one-letter prefixes on the first word
 * ("=אתר": "באתר" is on site, not a website), and a '*' word stands for any one word ("הנחת *").
 * Spelling variants (geresh/gershayim/no punctuation, "No."/"#"/"Nr.", "מס'"/"מספר", Hebrew
 * prefixes, the definite article on later words either way, "ת." for תאריך, Latin plurals,
 * accents, case) are generated by the matcher, so the data lists each phrase once in its most
 * common spelling.
 */
export interface ConceptSpec {
  id: string
  kind: ConceptKind
  /** Canonical fields the label can name (party attributes list both supplier and customer). */
  fields: readonly CanonicalField[]
  /** For 'doctype' concepts. */
  docType?: DocumentType
  /** The value kinds a label of this concept is followed by, best first. */
  values: readonly ValueKind[]
  /** Why the concept exists or what not to confuse it with. */
  note?: string
  phrases: Partial<Record<Lang, readonly string[]>>
}

/** A lexicon phrase found in a text. Offsets are UTF-16 offsets into the text as given. */
export interface LabelMatch {
  concept: string
  kind: ConceptKind
  fields: readonly CanonicalField[]
  /** The lexicon phrase that matched, as written in the lexicon (without '~'). */
  phrase: string
  /** The matched part of the input as printed (Hebrew prefix included). */
  text: string
  start: number
  end: number
  /** Hebrew one-letter prefixes in front of the phrase (folded, e.g. 'וה'), '' when none. */
  prefix: string
  strength: Strength
  language: Lang
  /** The phrase is the whole text, apart from punctuation and spaces ("תאריך:" but not "תאריך 1"). */
  exact: boolean
  /** Other concepts the very same span can name (e.g. "סה"כ" is subtotal, total or a column). */
  also: string[]
}

export type DateOrder = 'DMY' | 'MDY' | 'YMD'

export interface NumberFormat {
  decimal: '.' | ','
  group: ',' | '.' | ' ' | "'" | ''
  /** 0 when nothing on the document decided it (the default '.' was used), up to 1. */
  confidence: number
}

/** A parse always says where in the input it came from. */
export interface Span {
  /** The parsed part of the input as printed. */
  raw: string
  start: number
  end: number
}

export interface AmountParse extends Span {
  amount: DecimalString
  currency: string | null
  /**
   * True when the currency was read only from a mark several currencies share ("$", "¥", "Fr.",
   * "kr"): `currency` is then a default (or null for "kr"), and must not be verified without
   * another cue (see currencyAmbiguity, currencyFromLocaleCues). Absent otherwise.
   */
  currencyAmbiguous?: boolean
  negative: boolean
  /** Digits printed after the decimal separator. */
  decimals: number
  /** True when the reading of a lone separator ("1,234") was a default, not evidence. */
  ambiguous: boolean
  /** The other reading when ambiguous ("1.234" for "1,234" read as 1234). */
  alternative: DecimalString | null
}
